class QueueHandler(logging.Handler):
    """
    Logging handler that forwards formatted log records to a queue.

    This handler allows log messages generated by background threads to be
    safely transferred to the Gradio UI, where they can be displayed to the
    user without directly coupling the logging system to the UI.

    Attributes:
        log_queue: Queue used to store formatted log messages.
    """
    def __init__(self, log_queue):
        """
        Initialize the queue-based logging handler.

        Args:
            log_queue: Queue instance into which formatted log messages
                should be placed.
        """
        super().__init__()
        self.log_queue = log_queue

    def emit(self, record):
        """
        Format and enqueue a logging record.

        Args:
            record: Logging record produced by the Python logging framework.

        Returns:
            None.
        """
        self.log_queue.put(self.format(record))


def html_for(log_data):
    """
    Convert recent log messages into an HTML log viewer.

    Only the most recent 18 log messages are included. The resulting HTML
    contains a fixed-height, scrollable container suitable for displaying
    logs inside the Gradio interface.

    Args:
        log_data: List of formatted log messages.

    Returns:
        An HTML string containing the formatted log messages.
    """
    output = "<br>".join(log_data[-18:])
    return f"""
    <div id="scrollContent" style="height: 400px; overflow-y: auto; border: 1px solid #ccc; background-color: #222229; padding: 10px;">
    {output}
    </div>
    """


def setup_logging(log_queue):
    """
    Configure application logging to forward messages to a queue.

    Creates a ``QueueHandler`` with a timestamp-based formatter and attaches
    it to the root logger at INFO level. Log messages can subsequently be
    consumed by the Gradio UI.

    Args:
        log_queue: Queue that should receive formatted log messages.

    Returns:
        None.
    """
    handler = QueueHandler(log_queue)
    formatter = logging.Formatter(
        "[%(asctime)s] %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S %z",
    )
    handler.setFormatter(formatter)
    logger = logging.getLogger()
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)


class App:
    """
    Gradio application for interacting with the autonomous deal-finding system.

    The application provides a web-based interface that displays discovered
    deals, agent execution logs, and a 3D visualization of the product vector
    database.

    The underlying ``DealAgentFramework`` is initialized lazily and reused
    across application interactions.

    Attributes:
        agent_framework: Lazily initialized ``DealAgentFramework`` instance.
    """
    def __init__(self):
        """
        Initialize the application.

        The deal agent framework is not initialized immediately. It is created
        on demand the first time ``get_agent_framework()`` is called.
        """
        self.agent_framework = None

    def get_agent_framework(self):
        """
        Get the application's deal agent framework.

        Initializes the ``DealAgentFramework`` if it has not already been
        created, then returns the existing instance.

        Returns:
            The application's ``DealAgentFramework`` instance.
        """
        if not self.agent_framework:
            self.agent_framework = DealAgentFramework()
        return self.agent_framework

    def run(self):
        """
        Build and launch the Gradio application.

        Creates the user interface, configures the opportunities table,
        real-time logging output, periodic deal scanning, and 3D product
        embedding visualization.

        The interface automatically runs the deal-finding workflow when
        loaded and subsequently every five minutes using a Gradio timer.

        Returns:
            None.
        """
        with gr.Blocks(title="The Price is Right", fill_width=True) as ui:
            log_data = gr.State([])

            def table_for(opps):
                """
                Convert deal opportunities into rows for the Gradio dataframe.

                Args:
                    opps: Iterable of opportunity objects containing deal,
                        estimated value, and discount information.

                Returns:
                    A list of rows containing the product description, deal price,
                    estimated value, discount, and deal URL.
                """
                return [
                    [
                        opp.deal.product_description,
                        f"${opp.deal.price:.2f}",
                        f"${opp.estimate:.2f}",
                        f"${opp.discount:.2f}",
                        opp.deal.url,
                    ]
                    for opp in opps
                ]

            def update_output(log_data, log_queue, result_queue):
                """
                Stream logging and deal results from background queues to the UI.

                Continuously checks the logging and result queues and yields updated
                UI state to Gradio. Logging messages are formatted and displayed
                as they arrive, while the final deal results replace the initial
                opportunity table when the background workflow completes.

                Args:
                    log_data: Existing list of log messages displayed by the UI.
                    log_queue: Queue containing log messages from the worker thread.
                    result_queue: Queue containing the completed deal-finding
                        results.

                Yields:
                    Tuples containing the updated log state, rendered HTML logs,
                    and current opportunity table.
                """
                initial_result = table_for(self.get_agent_framework().memory)
                final_result = None
                while True:
                    try:
                        message = log_queue.get_nowait()
                        log_data.append(reformat(message))
                        yield log_data, html_for(log_data), final_result or initial_result
                    except queue.Empty:
                        try:
                            final_result = result_queue.get_nowait()
                            yield log_data, html_for(log_data), final_result or initial_result
                        except queue.Empty:
                            if final_result is not None:
                                break
                            time.sleep(0.1)

            def get_initial_plot():
                """
                Create a placeholder Plotly figure while vector data loads.

                Returns:
                    A Plotly figure displaying a loading message.
                """
                fig = go.Figure()
                fig.update_layout(
                    title="Loading vector DB...",
                    height=400,
                )
                return fig

            def get_plot():
                """
                Generate a 3D Plotly visualization of the product embeddings.

                Retrieves product embedding data from the ``DealAgentFramework``,
                then creates a 3D scatter plot where each point represents a
                product and its color corresponds to its product category.

                Returns:
                    A Plotly ``Figure`` containing the 3D product embedding
                    visualization.
                """
                documents, vectors, colors = DealAgentFramework.get_plot_data(max_datapoints=800)
                # Create the 3D scatter plot
                fig = go.Figure(
                    data=[
                        go.Scatter3d(
                            x=vectors[:, 0],
                            y=vectors[:, 1],
                            z=vectors[:, 2],
                            mode="markers",
                            marker=dict(size=2, color=colors, opacity=0.7),
                        )
                    ]
                )

                fig.update_layout(
                    scene=dict(
                        xaxis_title="x",
                        yaxis_title="y",
                        zaxis_title="z",
                        aspectmode="manual",
                        aspectratio=dict(x=2.2, y=2.2, z=1),  # Make x-axis twice as long
                        camera=dict(
                            eye=dict(x=1.6, y=1.6, z=0.8)  # Adjust camera position
                        ),
                    ),
                    height=400,
                    margin=dict(r=5, b=1, l=5, t=2),
                )

                return fig

            def do_run():
                """
                Execute the deal-finding workflow and prepare its results for the UI.

                Runs the ``DealAgentFramework``, retrieves all currently known
                opportunities, and converts them into rows suitable for the
                opportunities dataframe.

                Returns:
                    A list of dataframe rows representing discovered opportunities.
                """
                new_opportunities = self.get_agent_framework().run()
                table = table_for(new_opportunities)
                return table

            def run_with_logging(initial_log_data):
                """
                Run the deal-finding workflow in a background thread.

                Sets up queues for log messages and results, starts the agent
                workflow in a worker thread, and streams log and result updates
                back to the Gradio interface.

                Args:
                    initial_log_data: Existing log messages maintained by the
                        Gradio state.

                Yields:
                    Updated log state, rendered log HTML, and opportunity table
                    data as the background workflow progresses.
                """
                log_queue = queue.Queue()
                result_queue = queue.Queue()
                setup_logging(log_queue)

                def worker():
                    """
                    Execute the deal-finding workflow in the background thread.

                    Places the completed opportunity table into the result queue
                    after the framework finishes running.

                    Returns:
                        None.
                    """
                    result = do_run()
                    result_queue.put(result)

                thread = threading.Thread(target=worker)
                thread.start()

                for log_data, output, final_result in update_output(
                    initial_log_data, log_queue, result_queue
                ):
                    yield log_data, output, final_result

            def do_select(selected_index: gr.SelectData):
                """
                Handle selection of an opportunity in the dataframe.

                Retrieves the selected opportunity from the framework's memory
                based on the selected dataframe row. This function currently does
                not perform any further action with the selected opportunity.

                Args:
                    selected_index: Gradio selection event containing the index of
                        the selected dataframe row.

                Returns:
                    None.
                """
                opportunities = self.get_agent_framework().memory
                row = selected_index.index[0]
                opportunity = opportunities[row]
                # self.get_agent_framework().planner.messenger.alert(opportunity)

            with gr.Row():
                gr.Markdown(
                    '<div style="text-align: center;font-size:24px"><strong>The Price is Right</strong> - Autonomous Agent Framework that hunts for deals</div>'
                )
            with gr.Row():
                gr.Markdown(
                    '<div style="text-align: center;font-size:14px">A proprietary fine-tuned LLM deployed on Modal and a RAG pipeline with a frontier model collaborate to send push notifications with great online deals.</div>'
                )
            with gr.Row():
                opportunities_dataframe = gr.Dataframe(
                    headers=["Deals found so far", "Price", "Estimate", "Discount", "URL"],
                    wrap=True,
                    column_widths=[6, 1, 1, 1, 3],
                    row_count=10,
                    col_count=5,
                    max_height=400,
                )
            with gr.Row():
                with gr.Column(scale=1):
                    logs = gr.HTML()
                with gr.Column(scale=1):
                    plot = gr.Plot(value=get_plot(), show_label=False)

            ui.load(
                run_with_logging,
                inputs=[log_data],
                outputs=[log_data, logs, opportunities_dataframe],
            )

            timer = gr.Timer(value=300, active=True)
            timer.tick(
                run_with_logging,
                inputs=[log_data],
                outputs=[log_data, logs, opportunities_dataframe],
            )

            opportunities_dataframe.select(do_select)

        ui.launch(share=False, inbrowser=True)


if __name__ == "__main__":
    app = App()
    app.run()